const MESES_ES = ["ene", "feb", "mar", "abr", "may", "jun", "jul", "ago", "sep", "oct", "nov", "dic"];

/** «21 oct» o «10月21日». */
export function fechaCorta(d: string | null, idioma: Idioma): string {
  if (!d) return "—";
  const mes = Number(d.slice(5, 7));
  const dia = Number(d.slice(8, 10));
  return idioma === "zh" ? `${mes}月${dia}日` : `${dia} ${MESES_ES[mes - 1]}`;
}

