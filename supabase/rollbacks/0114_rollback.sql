create temporary table _revertir on commit drop as
select s.id, s.numero, s.codigo as actual, (1000 + c.numero)::text as viejo
from _cambio_sku c
join skus_maestros s on s.numero = c.numero
where btrim(s.codigo) = c.nuevo;

update skus_maestros s set codigo = r.viejo from _revertir r where s.id = r.id;
update wms_producto_variantes v set sku = r.viejo from _revertir r where v.sku_maestro_id = r.id;
update wms_dropi_productos d set sku = r.viejo from _revertir r where d.sku_maestro_id = r.id;

insert into historial_auditoria (usuario_nombre, accion, entidad, entidad_id, detalle, antes, despues)
select 'Reversión 0114', 'cambiar_sku_producto', 'skus_maestros', r.id::text, null, jsonb_build_object('SKU', r.actual), jsonb_build_object('SKU', r.viejo)
from _revertir r;

