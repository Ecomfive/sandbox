-- Pedir a inventario (16 nov 2026, pedido de Hernán; prototipo aprobado https://claude.ai/artifact/ReVGwYZrBG11rmKFUT7V5T).
-- Despacho le pide a inventario (Dinora) lo que se le agotó; inventario lo pone en proceso y lo envía (eso hace el traslado
-- a la bodega de despacho con `wms_crear_traslado`); despacho marca «Recibido». Reemplaza el Excel de solicitudes. Por ahora, Panamá.

create table if not exists despacho_pedidos_inventario (
  id uuid primary key default gen_random_uuid(),
  numero integer generated by default as identity unique,
  estado text not null default 'solicitud' check (estado in ('solicitud', 'en_proceso', 'enviado', 'recibido', 'cancelado')),
  bodega_destino_id uuid not null references wms_bodegas (id),
  bodega_origen_id uuid references wms_bodegas (id),
  traslado_id uuid references wms_traslados (id),
  pedido_por uuid not null,
  pedido_por_nombre text,
  creado_en timestamptz not null default now(),
  responsable_id uuid,
  responsable_nombre text,
  en_proceso_en timestamptz,
  enviado_en timestamptz,
  recibido_por uuid,
  recibido_por_nombre text,
  recibido_en timestamptz,
  cancelado_en timestamptz
);
create index if not exists despacho_pedidos_inventario_abiertos_idx on despacho_pedidos_inventario (creado_en) where estado in ('solicitud', 'en_proceso', 'enviado');
create index if not exists despacho_pedidos_inventario_creado_idx on despacho_pedidos_inventario (creado_en desc);

create table if not exists despacho_pedidos_inventario_items (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references despacho_pedidos_inventario (id) on delete cascade,
  orden smallint not null default 0,
  sku_id uuid not null references skus_maestros (id),
  producto text not null check (length(producto) <= 300),
  codigo text,
  cantidad_pedida integer not null check (cantidad_pedida between 1 and 1000000),
  nota text check (nota is null or length(nota) <= 300),
  cantidad_entregada integer check (cantidad_entregada is null or cantidad_entregada between 0 and 1000000),
  observacion text check (observacion is null or length(observacion) <= 300)
);
create index if not exists despacho_pedidos_inventario_items_pedido_idx on despacho_pedidos_inventario_items (pedido_id, orden);

-- Solo el servidor (clave de servicio) las lee y las escribe.
alter table despacho_pedidos_inventario enable row level security;
alter table despacho_pedidos_inventario_items enable row level security;

-- Pedir: los roles y las personas que tienen Despacho ciudad (Admin, CEO y Yiletsi). Atender: los mismos roles (Admin y CEO)
-- y Dinora como permiso propio (a ella le llegan los avisos de pedidos nuevos).
insert into permisos_rol (rol_id, modulo, solo_lectura)
select rol_id, 'despacho-pedir-inventario', solo_lectura from permisos_rol where modulo = 'despacho-ciudad'
on conflict (rol_id, modulo) do nothing;
insert into permisos_persona (perfil_id, modulo, nivel)
select perfil_id, 'despacho-pedir-inventario', nivel from permisos_persona where modulo = 'despacho-ciudad' and nivel <> 'ninguno'
on conflict (perfil_id, modulo) do nothing;
insert into permisos_rol (rol_id, modulo, solo_lectura)
select rol_id, 'inventario-pedidos-despacho', solo_lectura from permisos_rol where modulo = 'despacho-ciudad'
on conflict (rol_id, modulo) do nothing;
insert into permisos_persona (perfil_id, modulo, nivel)
select id, 'inventario-pedidos-despacho', 'edicion' from perfiles where nombre ilike 'Dinora %' and activo
on conflict (perfil_id, modulo) do nothing;

